    private void simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanActionPerformed
       // Validasi
        if (namaSupplier.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Supplier tidak boleh kosong!");
            namaSupplier.requestFocus();
            return;
        }
        if (telepon.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Telepon tidak boleh kosong!");
            telepon.requestFocus();
            return;
        }

        try {
            String newID = idSupplier.getText(); // ambil dari field yang sudah di-generate

            String sql = "INSERT INTO supplier (ID_Supplier, Nama_Supplier, Alamat, Telepon, Email, Pic) "
                       + "VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, newID);
            ps.setString(2, namaSupplier.getText().trim());
            ps.setString(3, alamat.getText().trim());
            ps.setString(4, telepon.getText().trim());
            ps.setString(5, email.getText().trim());
            ps.setString(6, pic.getText().trim());
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Supplier berhasil disimpan!\nID: " + newID);
            clearForm();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
        }
    }//GEN-LAST:event_simpanActionPerformed

