    private void simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanActionPerformed
        if (namaPegawai.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Pegawai tidak boleh kosong!");
            namaPegawai.requestFocus();
            return;
        }
        if (telepon.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Telepon tidak boleh kosong!");
            telepon.requestFocus();
            return;
        }

        try {
            String newID   = idSupplier.getText();
            String nama    = namaPegawai.getText().trim();
            String telp    = telepon.getText().trim();
            String mail    = email.getText().trim();
            String jabatan = jComboBox1.getSelectedItem().toString().trim();

            // Ambil nilai dari spinner
            java.util.Date tgl    = (java.util.Date) tanggalBergabung.getValue();
            java.sql.Date tanggal = new java.sql.Date(tgl.getTime());

            String sql = "INSERT INTO pegawai "
                       + "(ID_Pegawai, Nama_Pegawai, Email, Telepon, Jabatan, Tanggal_Bergabung) "
                       + "VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, newID);
            ps.setString(2, nama);
            ps.setString(3, mail);
            ps.setString(4, telp);
            ps.setString(5, jabatan);
            ps.setDate(6, tanggal);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Pegawai berhasil disimpan!\nID: " + newID);
            clearForm();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
        }
    }//GEN-LAST:event_simpanActionPerformed

