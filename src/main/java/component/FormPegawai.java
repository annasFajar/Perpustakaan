    private void autoIDPegawai() {
        try {
            String newID = "PGW001";
            ResultSet rs = conn.createStatement().executeQuery(
                "SELECT ID_Pegawai FROM pegawai ORDER BY ID_Pegawai DESC LIMIT 1");
            if (rs.next()) {
                int angka = Integer.parseInt(rs.getString(1).replaceAll("[^0-9]", "")) + 1;
                newID = String.format("PGW%03d", angka);
            }
            idSupplier.setText(newID);
        } catch (Exception e) {
            idSupplier.setText("PGW001");
        }
    }

