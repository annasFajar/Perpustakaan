    private void cariBarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cariBarangActionPerformed
        String keyword = cariBarang.getText().trim().toLowerCase();

        // Jika kosong atau placeholder, tampilkan semua
        if (keyword.isEmpty() || keyword.equals("cari nama / kode barang...")) {
            loadBarang();
            return;
        }

        try {
            conn = koneksi.getConnection();
            ResultSet rs = conn.createStatement().executeQuery(
                "SELECT b.Kode_Barang, b.Nama_Barang, k.Nama_Kategori, " +
                "b.Harga_Jual, b.Stok, " +
                "CASE " +
                "  WHEN b.Stok <= b.Stok_Minimum THEN 'Kritis' " +
                "  WHEN b.Stok <= b.Stok_Minimum * 2 THEN 'Menipis' " +
                "  ELSE 'Aman' " +
                "END AS Status " +
                "FROM barang b " +
                "JOIN kategori k ON b.Kategori_ID_Kategori = k.ID_Kategori " +
                "WHERE LOWER(b.Kode_Barang) LIKE '%" + keyword + "%' " +
                "   OR LOWER(b.Nama_Barang) LIKE '%" + keyword + "%' " +
                "   OR LOWER(k.Nama_Kategori) LIKE '%" + keyword + "%' " +
                "ORDER BY b.Kode_Barang ASC");

            DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("Kode_Barang"),
                    rs.getString("Nama_Barang"),
                    rs.getString("Nama_Kategori"),
                    "Rp " + String.format("%,.0f", rs.getDouble("Harga_Jual")),
                    rs.getInt("Stok"),
                    rs.getString("Status")
                });
            }

            // Info jika tidak ditemukan
            if (model.getRowCount() == 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Barang dengan kata kunci \"" + keyword + "\" tidak ditemukan.");
                loadBarang(); // kembali tampilkan semua
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mencari: " + e.getMessage());
        }
    }//GEN-LAST:event_cariBarangActionPerformed


