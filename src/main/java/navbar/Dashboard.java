    public void loadDashboard() {
        try {
            
            conn = koneksi.getConnection();
            // 1. Total Barang
            ResultSet rs1 = conn.createStatement().executeQuery(
                "SELECT COUNT(*) FROM Barang");
            rs1.next();
            jLabel6.setText(String.valueOf(rs1.getInt(1)));

            // 2. Total Kategori
            ResultSet rs2 = conn.createStatement().executeQuery(
                "SELECT COUNT(*) FROM Kategori");
            rs2.next();
            jLabel11.setText(rs2.getInt(1) + "");
            jLabel19.setText(rs2.getInt(1) + "");
            jLabel26.setText(rs2.getInt(1) + "");

            // 3. Transaksi Hari Ini
            ResultSet rs3 = conn.createStatement().executeQuery(
                "SELECT COUNT(*) FROM Penjualan " +
                "WHERE DATE(Tanggal_Penjualan)");
            rs3.next();
            jLabel17.setText(String.valueOf(rs3.getInt(1)));

            // 4. Omzet Hari Ini
            ResultSet rs4 = conn.createStatement().executeQuery(
                "SELECT COALESCE(SUM(Total),0) FROM Penjualan " +
                "WHERE DATE(Tanggal_Penjualan)");
            rs4.next();
            double omzet = rs4.getDouble(1);
            jLabel32.setText("Rp " + formatJuta(omzet) + "");

            // 5. Stok Kritis
            ResultSet rs5 = conn.createStatement().executeQuery(
                "SELECT COUNT(*) FROM Barang " +
                "WHERE Stok <= Stok_Minimum");
            rs5.next();
            jLabel29.setText(String.valueOf(rs5.getInt(1) + ""));
            
            ResultSet rs6 = conn.createStatement().executeQuery(
                "SELECT No_Nota, Nama_Pembeli, Total FROM penjualan " +
                "WHERE DATE(Tanggal_Penjualan)" +
                "ORDER BY Tanggal_Penjualan DESC LIMIT 5");
            
            

            DefaultTableModel modelPenjualan = (DefaultTableModel) jTable3.getModel();
            modelPenjualan.setRowCount(0); // kosongkan dulu
            while (rs6.next()) {
                modelPenjualan.addRow(new Object[]{
                    rs6.getString("No_Nota"),
                    rs6.getString("Nama_Pembeli"),
                    "Rp " + formatJuta(rs6.getDouble("Total")),
                    "Lunas"
                });
            }

            // Tabel Status Stok
            ResultSet rs7 = conn.createStatement().executeQuery(
                "SELECT Nama_Barang, Stok, Stok_Minimum, " +
                "CASE " +
                "  WHEN Stok <= Stok_Minimum THEN 'Kritis' " +
                "  WHEN Stok <= Stok_Minimum * 2 THEN 'Menipis' " +
                "  ELSE 'Aman' " +
                "END AS Status " +
                "FROM barang ORDER BY Stok ASC LIMIT 10");

            DefaultTableModel modelStok = (DefaultTableModel) jTable2.getModel();
            modelStok.setRowCount(0); // kosongkan dulu
            while (rs7.next()) {
                modelStok.addRow(new Object[]{
                    rs7.getString("Nama_Barang"),
                    rs7.getInt("Stok"),
                    rs7.getString("Status")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal load dashboard: " + e.getMessage());
        }
    }
    
