// Format angka ke "4,7jt" / "850rb"
    private String formatJuta(double angka) {
        if (angka >= 1_000_000)
            return String.format("%.1fjt", angka / 1_000_000).replace(".0jt", "jt");
        else if (angka >= 1_000)
            return String.format("%.0frb", angka / 1_000);
        else
            return String.valueOf((long) angka);
    }

