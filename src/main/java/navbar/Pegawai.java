    private void cariPegawaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cariPegawaiActionPerformed
        String keyword = cariPegawai.getText().trim().toLowerCase();

        if (keyword.isEmpty() || keyword.equals("cari nama / kode pegawai...")) {
            loadPegawai();
            return;
        }

        try {
            conn = koneksi.getConnection();
            ResultSet rs = conn.createStatement().executeQuery(
                "SELECT ID_Pegawai, Nama_Pegawai, Jabatan, Telepon " +
                "FROM pegawai " +
                "WHERE LOWER(ID_Pegawai)   LIKE '%" + keyword + "%' " +
                "   OR LOWER(Nama_Pegawai) LIKE '%" + keyword + "%' " +
                "   OR LOWER(Jabatan)      LIKE '%" + keyword + "%' " +
                "   OR LOWER(Telepon)      LIKE '%" + keyword + "%' " +
                "ORDER BY ID_Pegawai ASC");

            DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("ID_Pegawai"),
                    rs.getString("Nama_Pegawai"),
                    rs.getString("Jabatan"),
                    rs.getString("Telepon")
                });
            }

            if (model.getRowCount() == 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Pegawai dengan kata kunci \"" + keyword + "\" tidak ditemukan.");
                loadPegawai();
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mencari: " + e.getMessage());
        }
    }//GEN-LAST:event_cariPegawaiActionPerformed

