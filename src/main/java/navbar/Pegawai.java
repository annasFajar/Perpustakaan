    public void loadPegawai() {
    try {
        conn = koneksi.getConnection();

        // Total pegawai
        ResultSet rsTotal = conn.createStatement().executeQuery(
            "SELECT COUNT(*) FROM pegawai");
        rsTotal.next();
        nav14.setText("Daftar Pegawai  |  " + rsTotal.getInt(1) + " pegawai");

        // Data tabel
        ResultSet rs = conn.createStatement().executeQuery(
            "SELECT ID_Pegawai, Nama_Pegawai, Jabatan, Telepon " +
            "FROM pegawai ORDER BY ID_Pegawai ASC");

        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        model.setRowCount(0);
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("ID_Pegawai"),
                rs.getString("Nama_Pegawai"),
                rs.getString("Jabatan"),
                rs.getString("Telepon"),
                "Edit"
            });
        }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal load pegawai: " + e.getMessage());
        }
    }

